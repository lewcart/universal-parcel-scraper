import { accepted, recognizeFromLookup, type AdapterFactory, type TrackingContext } from '../../core/adapter/index.js';
import { ChallengeError, SchemaError, TransportError, UpstreamHttpError } from '../../core/errors/index.js';
import type { CarrierResult } from '../../core/result/index.js';
import { runSteps } from '../../core/runner/index.js';
import { firstAttemptMs, networkRetryStep } from '../../core/runner/networkRetry.js';
import { NOOP_RECORDER, type StepRecorder } from '../../core/telemetry/index.js';
import { decodeText, fetchBounded, parseJsonBytes, userAgentOf } from '../../core/transport/index.js';
import { LATVIJAS_PASTS_MAX_BYTES, normalizeLatvijasPastsNumber, parseLatvijasPasts, PROVIDER } from './parser.js';

// The service mans.pasts.lv's tracking page reads. It answers JSON only when
// asked for it, and XML otherwise.
export const LATVIJAS_PASTS_ENDPOINT = 'https://mans.pasts.lv/tracking-api';
// A CloudFront or web application firewall block page.
const BLOCKED = /<title>\s*(?:ERROR: The request could not be satisfied|Request blocked|Access Denied|Just a moment|Attention Required)|cf-chl-|cf-turnstile|Generated by cloudfront/i;

export class LatvijasPastsTracker {
  constructor(private readonly options: { fetcher?: typeof fetch; recorder?: StepRecorder; userAgent?: string } = {}) {}

  async fetch(raw: string, context: TrackingContext = {}): Promise<CarrierResult> {
    const number = normalizeLatvijasPastsNumber(raw);
    const url = `${LATVIJAS_PASTS_ENDPOINT}?${new URLSearchParams({ id: number, lang: 'en-US', include_group: 'true' })}`;
    const read = async (signal: AbortSignal, timeoutMs: number): Promise<CarrierResult> => {
      let bytes: Uint8Array;
      try {
        ({ bytes } = await fetchBounded(url, { signal, headers: { Accept: 'application/json', 'User-Agent': userAgentOf(this.options.userAgent) } },
          { provider: PROVIDER, timeoutMs: Math.max(1, Math.floor(timeoutMs)), maxBytes: LATVIJAS_PASTS_MAX_BYTES, fetcher: this.options.fetcher }));
      } catch (error) {
        // A missing route is not a missing item: the service answers unknown codes with a notice.
        if (error instanceof UpstreamHttpError && [404, 410].includes(error.status)) {
          throw new TransportError(PROVIDER, 'Latvijas Pasts tracking endpoint is unavailable', { cause: error });
        }
        throw error;
      }
      let payload: unknown;
      try { payload = parseJsonBytes(bytes, PROVIDER); }
      catch (cause) {
        if (BLOCKED.test(decodeText(bytes.subarray(0, 64_000)))) throw new ChallengeError(PROVIDER, 'Latvijas Pasts answered with a block page', { cause });
        throw new SchemaError(PROVIDER, 'Latvijas Pasts returned invalid tracking JSON', { cause });
      }
      return parseLatvijasPasts(payload, number);
    };
    // A request that fails to reach Latvijas Pasts, or hangs, gets one more
    // try: the first gets half of the budget, so the retry fits in the rest.
    return runSteps({ carrier: 'latvijas-pasts', budgetMs: context.budgetMs ?? 15_000, signal: context.signal,
      recorder: this.options.recorder ?? NOOP_RECORDER }, [
      { id: 'direct', run: ({ signal, remainingMs }) => read(signal, firstAttemptMs(remainingMs)) },
      networkRetryStep(({ signal, remainingMs }) => read(signal, remainingMs)),
    ]);
  }
}

export const adapter: AdapterFactory = (environment) => {
  const tracker = new LatvijasPastsTracker({ fetcher: environment.fetcher, recorder: environment.recorder, userAgent: environment.userAgent });
  return {
    id: 'latvijas-pasts', recordsSteps: true, steps: ['direct', 'retry'],
    track: (input, context) => tracker.fetch(input.number, context),
    recognize: (number, context) => recognizeFromLookup(() => tracker.fetch(number, context),
      () => accepted(() => normalizeLatvijasPastsNumber(number))),
  };
};
