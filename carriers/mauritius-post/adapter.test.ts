import { readFileSync } from 'node:fs';
import { describe, expect, it, vi } from 'vitest';
import { statusMapAnswer } from '../../core/catalog/statusMaps.js';
import { parseTrackingInput } from '../../core/detection/index.js';
import { UpstreamNetworkError } from '../../core/errors/index.js';
import { NOOP_RECORDER } from '../../core/telemetry/index.js';
import { createTracker } from '../../facade/index.js';
import { adapter, MAURITIUS_POST_TRACKING, MauritiusPostTracker } from './adapter.js';
import { mauritiusPostUrl, normalizeMauritiusPostNumber, parseMauritiusPost } from './parser.js';
import { mauritiusPostStage, statusMap } from './status.js';
import statuses from './statuses.json' with { type: 'json' };
import { fakeBudgetClock } from '../../testing/budgetClock.js';

const DELIVERED = 'DP000000014MU';
const IN_TRANSIT = 'DP000000028MU';
const UNKNOWN = 'RR000000031MU';
// A French item sent to Mauritius.
const INBOUND = 'CP000000045FR';

const fixture = (name: string) => readFileSync(new URL(`./fixtures/${name}.html`, import.meta.url), 'utf8');
const reply = (body: string, init: ResponseInit = {}) => new Response(body, { ...init, headers: { 'Content-Type': 'text/html; charset=UTF-8', ...init.headers } });
const answering = (body: () => Response) => vi.fn<typeof fetch>().mockImplementation(async () => body());
const carrier = (fetcher: typeof fetch) => adapter({ fetcher, recorder: NOOP_RECORDER, env: {}, trawl: null, browserExecutablePath: null });
const CLOUDFLARE = '<!DOCTYPE html><html><head><title>Just a moment...</title></head><body><script>window._cf_chl_opt={}</script></body></html>';
// Wordfence's pages, which the site's firewall serves with HTTP 503.
const WORDFENCE_BLOCK = '<html><head><title>Your access to this site has been limited by the site owner</title></head><body><h1>Your access to this site has been limited by the site owner</h1><p>Generated by Wordfence</p></body></html>';
const WORDFENCE_THROTTLE = '<html><head><title>Your access to this service has been limited</title></head><body><h1>Your access to this service has been temporarily limited. Please try again in a few minutes.</h1><p>Generated by Wordfence</p></body></html>';

describe('Mauritius Post HTTP adapter', () => {
  it('asks the tracking page about the whole number once, through the supplied transport', async () => {
    const fetcher = answering(() => reply(fixture('in-transit')));
    const recorder = { ...NOOP_RECORDER, step: vi.fn(), lookup: vi.fn() };
    await expect(new MauritiusPostTracker({ fetcher, recorder, userAgent: 'SyntheticHost/1.0' }).fetch(' dp 000 000 028 mu ', { budgetMs: 1000.5 }))
      .resolves.toMatchObject({ current_stage: 'in_transit' });
    expect(fetcher).toHaveBeenCalledTimes(1);
    const [url, init] = fetcher.mock.calls[0]!;
    expect(String(url)).toBe(`${MAURITIUS_POST_TRACKING}?tracking_code=${IN_TRANSIT}`);
    expect(mauritiusPostUrl(IN_TRANSIT)).toBe(String(url));
    expect(init).toMatchObject({ method: 'GET', redirect: 'manual', signal: expect.any(AbortSignal),
      headers: { Accept: 'text/html,application/xhtml+xml', 'User-Agent': 'SyntheticHost/1.0' } });
    expect(recorder.step).toHaveBeenCalledWith(expect.objectContaining({ carrier: 'mauritius-post', step: 'direct', outcome: 'ok' }));
    expect(recorder.lookup).toHaveBeenCalledTimes(1);
  });

  it('reads a delivered item newest first on its wall clocks, once each, without the estimate', async () => {
    const result = await carrier(answering(() => reply(fixture('delivered')))).track({ number: DELIVERED });
    expect(result).toMatchObject({
      status: 'delivered', current_stage: 'delivered', current_stage_source: 'carrier_map', last_status_text: 'Delivered Through Counter',
      last_update: null, last_update_local: '2026-03-13T10:43:00', expected_delivery: null,
    });
    expect(result.events!.map((event) => [event.local_time, event.location, event.description, event.stage])).toEqual([
      ['2026-03-13T10:43:00', 'Sample Bay', 'Delivered Through Counter', 'delivered'],
      ['2026-03-13T10:41:00', 'Sample Bay', 'Delivery Notification Generated', 'ready_for_pickup'],
      // Scans of the same minute keep the page's order, newest last; the repeated one counts once.
      ['2026-03-12T16:02:00', 'Sample Bay', 'Received From Bag', 'in_transit'],
      ['2026-03-12T16:02:00', 'Sample Bay', 'Receive an item at office of delivery', 'in_transit'],
      ['2026-03-12T13:30:00', 'Exampleville', 'Dispatched', 'in_transit'],
      ['2026-03-12T09:14:00', 'Exampleville', 'Receipt Label Printed', 'accepted'],
      ['2026-03-12T07:05:00', 'Virtual Office', 'Received From Customer', 'accepted'],
    ]);
    expect(result.events!.every((event) => event.time === undefined && event.stage_source === 'carrier_map')).toBe(true);
    expect(JSON.stringify(result)).not.toMatch(/13-Mar|1 days|EDIT7/);
  });

  it('reads an item on its way in the earlier wording, echoed in lower case, without an estimate', () => {
    const result = parseMauritiusPost(fixture('in-transit'), IN_TRANSIT);
    expect(result).toMatchObject({ status: 'in_transit', current_stage: 'in_transit', last_status_text: 'Dispatched', last_update_local: '2026-07-02T12:20:00' });
    expect(result.events!.map((event) => [event.description, event.stage])).toEqual([
      ['Dispatched', 'in_transit'], ['Pacakge label printed', 'accepted'], ['Received the shipment from customer', 'accepted'],
    ]);
    expect(JSON.stringify(result)).not.toMatch(/Invalid date/);
  });

  it('takes items other posts send to Mauritius by their own S10 number', async () => {
    const page = fixture('delivered').replaceAll(DELIVERED, INBOUND);
    const fetcher = answering(() => reply(page));
    await expect(carrier(fetcher).track({ number: INBOUND })).resolves.toMatchObject({ current_stage: 'delivered' });
    expect(String(fetcher.mock.calls[0]![0])).toBe(mauritiusPostUrl(INBOUND));
  });

  it('leaves wording the map lacks to the shared rules, and without a stage when they do not know it either', () => {
    const page = (wording: string) => fixture('in-transit').replace('Dispatched', wording);
    expect(parseMauritiusPost(page('Item delivered to addressee'), IN_TRANSIT)).toMatchObject({ current_stage: 'delivered',
      current_stage_source: expect.stringMatching(/^wording:/) });
    const unknown = parseMauritiusPost(page('Xyzzy'), IN_TRANSIT);
    expect(unknown).toMatchObject({ status: 'unknown', last_status_text: 'Xyzzy' });
    expect(unknown).not.toHaveProperty('current_stage');
    expect(unknown.events![0]).toEqual({ local_time: '2026-07-02T12:20:00', location: 'Exampleville', description: 'Xyzzy' });
  });

  it('reads the tracker’s no-information notice as not found', async () => {
    await expect(carrier(answering(() => reply(fixture('not-found')))).track({ number: UNKNOWN })).rejects.toMatchObject({ kind: 'not_found' });
  });

  it('refuses an answer about another number', () => {
    expect(() => parseMauritiusPost(fixture('delivered'), IN_TRANSIT)).toThrow(expect.objectContaining({ kind: 'schema' }));
    expect(() => parseMauritiusPost(fixture('not-found'), DELIVERED)).toThrow(expect.objectContaining({ kind: 'schema' }));
    // The form echoes the number asked, but the results name another.
    const other = fixture('delivered').replace(`<p class="tt-tracking-number">${DELIVERED}`, `<p class="tt-tracking-number">${IN_TRANSIT}`);
    expect(() => parseMauritiusPost(other, DELIVERED)).toThrow(expect.objectContaining({ kind: 'schema' }));
    expect(() => parseMauritiusPost(fixture('delivered').replace(`value="${DELIVERED}"`, 'value=""'), DELIVERED))
      .toThrow(expect.objectContaining({ kind: 'schema' }));
  });

  it('refuses a changed page and reads an item without scans as inconclusive', () => {
    const delivered = fixture('delivered');
    for (const page of [
      '<html><body>Track &amp; Trace</body></html>',
      // The form without the results, as the page renders without a number.
      delivered.replace(/<div class="track-and-trace-results-section">[\s\S]*<\/div><\/div><\/div><\/div><div class="elementor-element elementor-element-32c3c88/,
        '<div class="track-and-trace-results-section"></div></div></div></div><div class="elementor-element elementor-element-32c3c88'),
      fixture('not-found').replace('No tracking information available for this item', 'Service temporarily unavailable'),
      delivered.replace('13 March 2026</span>\n<span class="tt-status-time">10:43', '13 Smarch 2026</span>\n<span class="tt-status-time">10:43'),
      delivered.replace('<span class="tt-status-time">10:43', '<span class="tt-status-time">25:43'),
      delivered.replace('<p class="tt-status-comment">Dispatched</p>', '<p class="tt-status-comment"> </p>'),
      delivered.replace('<p class="tt-status-comment">Dispatched</p>', ''),
      delivered.replace('<p class="tt-tracking-number">', '<p class="tt-tracking-reference">'),
      // The newest scan is no longer the last one.
      delivered.replace('tt-status-block current-status', 'tt-status-block ').replace('<div class="tt-status-block ">', '<div class="tt-status-block current-status">'),
    ]) expect(() => parseMauritiusPost(page, DELIVERED), page.slice(-200)).toThrow(expect.objectContaining({ kind: 'schema' }));
    const empty = delivered.replace(/<div class="track-and-trace-results-status tt-body-column">[\s\S]*?<\/div><\/div><\/div><div class="elementor-element elementor-element-32c3c88/,
      '<div class="track-and-trace-results-status tt-body-column"></div></div></div><div class="elementor-element elementor-element-32c3c88');
    expect(() => parseMauritiusPost(empty, DELIVERED)).toThrow(expect.objectContaining({ kind: 'indeterminate', name: 'NoHistoryError' }));
  });

  it('keeps firewall pages, rate limits, server errors and moved routes apart from a missing item', async () => {
    const lookup = (answer: () => Response) => carrier(answering(answer)).track({ number: DELIVERED });
    await expect(lookup(() => reply(CLOUDFLARE))).rejects.toMatchObject({ kind: 'challenge' });
    await expect(lookup(() => reply(WORDFENCE_BLOCK, { status: 503 }))).rejects.toMatchObject({ kind: 'challenge' });
    await expect(lookup(() => reply(WORDFENCE_THROTTLE, { status: 503 }))).rejects.toMatchObject({ kind: 'rate_limited' });
    await expect(lookup(() => reply('Forbidden', { status: 403 }))).rejects.toMatchObject({ kind: 'challenge' });
    await expect(lookup(() => reply('Too Many Requests', { status: 429 }))).rejects.toMatchObject({ kind: 'rate_limited' });
    await expect(lookup(() => reply('<html><body>Internal Server Error</body></html>', { status: 500 }))).rejects.toMatchObject({ kind: 'indeterminate' });
    await expect(lookup(() => reply('<html><body>Service Unavailable</body></html>', { status: 503 }))).rejects.toMatchObject({ kind: 'maintenance' });
    await expect(lookup(() => reply('<html><body>Page not found</body></html>', { status: 404 }))).rejects.toMatchObject({ kind: 'transport' });
    await expect(lookup(() => reply('', { status: 301, headers: { Location: 'https://www.mauritiuspost.mu/' } }))).rejects.toMatchObject({ kind: 'transport' });
  });

  it('asks once more when Mauritius Post cannot be reached, inside the caller’s budget', async () => {
    const flaky = vi.fn<typeof fetch>().mockRejectedValueOnce(new TypeError('fetch failed')).mockResolvedValueOnce(reply(fixture('in-transit')));
    const recorder = { ...NOOP_RECORDER, step: vi.fn() };
    await expect(new MauritiusPostTracker({ fetcher: flaky, recorder }).fetch(IN_TRANSIT, { budgetMs: 2000 })).resolves.toMatchObject({ current_stage: 'in_transit' });
    expect(flaky).toHaveBeenCalledTimes(2);
    expect(recorder.step).toHaveBeenCalledWith(expect.objectContaining({ step: 'retry', outcome: 'ok' }));
    const failing = vi.fn<typeof fetch>().mockRejectedValue(new TypeError('fetch failed'));
    await expect(carrier(failing).track({ number: IN_TRANSIT }, { budgetMs: 2000 })).rejects.toBeInstanceOf(UpstreamNetworkError);
    expect(failing).toHaveBeenCalledTimes(2);
  });

  it('ends a hanging read inside the budget', async () => {
    const clock = fakeBudgetClock();
    const signals: AbortSignal[] = [];
    const fetcher = vi.fn<typeof fetch>((_input, init) => new Promise((_resolve, reject) => {
      const signal = init!.signal!;
      signals.push(signal);
      signal.addEventListener('abort', () => reject(signal.reason), { once: true });
    }));
    const started = Date.now();
    await clock.settle(expect(carrier(fetcher).track({ number: IN_TRANSIT }, { budgetMs: 80 })).rejects.toThrow());
    expect(signals.length).toBeGreaterThan(0);
    expect(signals.every((signal) => signal.aborted)).toBe(true);
    expect(Date.now() - started).toBeLessThan(2000);
  });

  it('rejects what is not an S10 item code, and pre-aborted lookups, without a request', async () => {
    const fetcher = vi.fn<typeof fetch>();
    for (const number of ['', 'DP000000015MU', 'DP00000001MU', 'DP0000000140MU', '000000014', 'order 1234', `${DELIVERED}${'0'.repeat(60)}`]) {
      await expect(carrier(fetcher).track({ number }), number).rejects.toMatchObject({ kind: 'invalid_input' });
    }
    await expect(carrier(fetcher).track({ number: IN_TRANSIT }, { signal: AbortSignal.abort(new Error('cancelled')) })).rejects.toThrow('cancelled');
    expect(fetcher).not.toHaveBeenCalled();
    expect(normalizeMauritiusPostNumber('dp 000 000 014 mu')).toBe(DELIVERED);
  });

  it('answers an item filed under Mauritius Post or opened from its tracking page’s address', async () => {
    const fetcher = answering(() => reply(fixture('in-transit')));
    const tracker = createTracker({ fetcher, providers: [], env: {} });
    await expect(tracker.track({ number: IN_TRANSIT, carrier: 'mauritius-post' }, { budgetMs: 3000 }))
      .resolves.toMatchObject({ carrier: 'mauritius-post', source: 'mauritius-post', result: { current_stage: 'in_transit' } });
    expect(fetcher.mock.calls.every(([url]) => String(url).startsWith(MAURITIUS_POST_TRACKING))).toBe(true);
    expect(parseTrackingInput(`https://www.mauritiuspost.mu/track-trace/?tracking_code=${IN_TRANSIT}`))
      .toMatchObject({ trackingNumber: IN_TRANSIT, carrier: 'mauritius-post' });
  });
});

describe('Mauritius Post status vocabulary', () => {
  it('records every wording seen with the stage the map gives it', () => {
    for (const entry of statuses.entries as { wording: string; stage?: string }[]) {
      expect(mauritiusPostStage(entry.wording), entry.wording).toEqual(entry.stage ? { stage: entry.stage, source: 'carrier_map' } : null);
    }
    expect(statusMapAnswer({ carrier: 'mauritius-post', providerCode: null, description: 'Delivered Through Counter' })).toEqual({ kind: 'mapped', stage: 'delivered' });
    expect(statusMapAnswer({ carrier: 'mauritius-post', providerCode: null, description: 'Xyzzy' })).toEqual({ kind: 'unknown' });
    expect(statusMap.gaps).toEqual([]);
  });
});
