import { load, type Cheerio } from 'cheerio';
import type { AnyNode } from 'domhandler';
import { isValidS10TrackingNumber, normalizeTrackingNumber } from '../../core/detection/index.js';
import { returnedTrackingNumber } from '../../core/detection/returned.js';
import { ChallengeError, InvalidInputError, NoHistoryError, NotFoundError, RateLimitedError, SchemaError } from '../../core/errors/index.js';
import type { CarrierEvent, CarrierResult } from '../../core/result/index.js';
import { languageStageStatus, type Stage } from '../../core/status/index.js';
import { calendarDay } from '../../core/time/index.js';
import { clean } from '../../core/transport/index.js';
import { mauritiusPostStage } from './status.js';

export const PROVIDER = 'Mauritius Post';
// The page is about 470 kB of styles and scripts; each scan adds under 1 kB.
export const MAURITIUS_POST_MAX_BYTES = 2_000_000;
/** The tracking page, which looks up the number in its `tracking_code` parameter on the server. */
export const MAURITIUS_POST_TRACKING = 'https://www.mauritiuspost.mu/track-trace/';

const MAX_SCANS = 500;
// The tracker's answer for a number it holds nothing for.
const NO_INFORMATION = 'No tracking information available for this item';
// "30 December 2025" and "07:37".
const DAY = /^(\d{1,2}) ([A-Za-z]{3,9}) (\d{4})$/;
const CLOCK = /^([01]?\d|2[0-3]):([0-5]\d)$/;
const MONTHS = ['january', 'february', 'march', 'april', 'may', 'june', 'july', 'august', 'september', 'october', 'november', 'december'];
// Wordfence, the site's firewall, limits a visitor who sends too many requests.
const THROTTLED = /Your access to this (?:site|service) has been temporarily limited|exceeded the maximum number of (?:requests|page)/i;
// A firewall's, CDN's or bot check's page in place of the tracker's, which can come back with HTTP 200.
const BLOCKED = /Generated by Wordfence|Your access to this site has been limited|potentially unsafe operation has been detected|<title>\s*(?:Access Denied|Attention Required|Just a moment|Request Rejected)|_cf_chl_opt|cf-turnstile|g-recaptcha|hcaptcha/i;

/**
 * Mauritius Post's tracker looks up UPU S10 item codes: its own, ending MU,
 * and those of the posts that send mail to Mauritius. The code needs a valid
 * check digit.
 */
export function normalizeMauritiusPostNumber(raw: string): string {
  const number = raw.length <= 64 ? normalizeTrackingNumber(raw) : '';
  if (isValidS10TrackingNumber(number)) return number;
  throw new InvalidInputError(PROVIDER, 'Mauritius Post tracks S10 item codes');
}

/** The tracking page's address for one number, as its form sends it. */
export function mauritiusPostUrl(number: string): string {
  return `${MAURITIUS_POST_TRACKING}?${new URLSearchParams({ tracking_code: number })}`;
}

/** A firewall's page: a rate limit, else a block, or null when the page is neither. */
export function mauritiusPostBlock(html: string): RateLimitedError | ChallengeError | null {
  const head = html.slice(0, 64_000);
  if (THROTTLED.test(head)) return new RateLimitedError(PROVIDER, undefined, 'Mauritius Post’s firewall limited the lookups');
  if (BLOCKED.test(head)) return new ChallengeError(PROVIDER, 'Mauritius Post answered with a block page');
  return null;
}

/** A page without what the tracker's has: a firewall's page, else a changed page. */
function unexpected(html: string, message: string): never {
  throw mauritiusPostBlock(html) ?? new SchemaError(PROVIDER, message);
}

/** The single element a selector must find in the scope. */
function one(scope: Cheerio<AnyNode>, selector: string): Cheerio<AnyNode> {
  const found = scope.find(selector);
  if (found.length !== 1) throw new SchemaError(PROVIDER, 'Mauritius Post’s tracking results changed');
  return found;
}

/** The wall clock of a scan, which the page gives without an offset. */
function clockOf(dayText: string, clockText: string): string {
  const day = DAY.exec(dayText);
  const month = day ? MONTHS.indexOf(day[2]!.toLowerCase()) + 1 : 0;
  const date = day && month ? calendarDay(Number(day[3]), month, Number(day[1])) : null;
  const clock = CLOCK.exec(clockText);
  if (!date || !clock) throw new SchemaError(PROVIDER, 'Mauritius Post returned a scan without a valid clock');
  return `${date}T${clock[1]!.padStart(2, '0')}:${clock[2]}:00`;
}

/** One status block: its day, time, office and wording. */
function scanOf(block: Cheerio<AnyNode>): CarrierEvent {
  const description = clean(one(block, '.tt-status-comment').text(), 300);
  if (!description) throw new SchemaError(PROVIDER, 'Mauritius Post returned a scan without wording');
  const location = clean(block.find('.tt-status-location').first().text(), 120);
  const event: CarrierEvent = {
    local_time: clockOf(clean(one(block, '.tt-status-date').text(), 40), clean(one(block, '.tt-status-time').text(), 20)),
    description,
    ...(location ? { location } : {}),
  };
  const classified = mauritiusPostStage(description);
  return classified ? { ...event, stage: classified.stage, stage_source: classified.source } : event;
}

/**
 * The tracking page for one number. The form's field echoes the number the
 * page looked up. A number the tracker holds comes back with a header naming
 * it and its scans, oldest first, the newest marked as the current status;
 * any other comes back with the no-information notice.
 */
export function parseMauritiusPost(html: string, rawNumber: string): CarrierResult {
  const number = normalizeMauritiusPostNumber(rawNumber);
  const $ = load(html);
  const sections = $('.track-and-trace-results-section');
  const field = $('form#track-and-trace-form input[name="tracking_code"]');
  if (sections.length !== 1 || field.length !== 1) unexpected(html, 'Mauritius Post did not return its tracking page');
  if (returnedTrackingNumber(field.attr('value') ?? '') !== number) {
    throw new SchemaError(PROVIDER, 'Mauritius Post answered for a different item');
  }
  const section = sections.first();
  const header = section.children('.track-and-trace-results-header');
  if (!header.length) {
    if (clean(section.text(), 200) === NO_INFORMATION) throw new NotFoundError(PROVIDER);
    throw new SchemaError(PROVIDER, 'Mauritius Post’s tracker answered with an unexpected notice');
  }
  if (returnedTrackingNumber(one(header, '.tt-tracking-number').text()) !== number) {
    throw new SchemaError(PROVIDER, 'Mauritius Post answered for a different item');
  }
  const blocks = one(section, '.track-and-trace-results-status').children('.tt-status-block');
  if (!blocks.length) throw new NoHistoryError(PROVIDER, 'Mauritius Post returned the item without a history', { reason: 'no_history' });
  if (blocks.length > MAX_SCANS) throw new SchemaError(PROVIDER, 'Mauritius Post returned an invalid item history');
  const current = blocks.filter('.current-status');
  if (current.length > 1 || (current.length === 1 && !blocks.last().is('.current-status'))) {
    throw new SchemaError(PROVIDER, 'Mauritius Post’s tracking results changed order');
  }

  const events: CarrierEvent[] = [];
  const seen = new Set<string>();
  blocks.each((_, node) => {
    const event = scanOf($(node));
    const identity = JSON.stringify(event);
    if (seen.has(identity)) return;
    seen.add(identity);
    events.push(event);
  });
  // Oldest first on the page; newest first here, scans at the same minute in the page's order reversed.
  events.reverse();

  const latest = events[0]!;
  const stage = latest.stage as Stage | undefined;
  return {
    status: stage ? languageStageStatus(stage) : 'unknown',
    ...(stage ? { current_stage: stage, current_stage_source: latest.stage_source } : {}),
    last_status_text: latest.description!,
    last_update: null,
    last_update_local: latest.local_time,
    expected_delivery: null,
    events,
  };
}
