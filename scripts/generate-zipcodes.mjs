// Builds places/zipcodes.json: the town a US ZIP Code's first three digits are
// named for, for USPS scans placed only at a ZIP Code ("ZIP Code 60600").
//
// Source: GeoNames US postal codes, CC BY 4.0, https://download.geonames.org/export/zip/US.zip.
// A prefix is a town's when the town holds most of its ZIP Codes; a prefix shared
// by many small towns gets no place. Military ZIP Codes have no town.
//
// Run: node scripts/generate-zipcodes.mjs [cache directory]. Needs `unzip`.
import { execFileSync } from 'node:child_process';
import { mkdir, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const cache = process.argv[2] ?? '/tmp/universal-parcel-scraper-places';
// The fewest ZIP Codes a town needs to be its prefix's.
const MIN_CODES = 3;

await mkdir(cache, { recursive: true });
const zip = join(cache, 'US-postal.zip');
if (!existsSync(zip)) {
  const response = await fetch('https://download.geonames.org/export/zip/US.zip');
  if (!response.ok) throw new Error(`US.zip: HTTP ${response.status}`);
  await writeFile(zip, Buffer.from(await response.arrayBuffer()));
}
const rows = execFileSync('unzip', ['-p', zip, 'US.txt'], { maxBuffer: 64 * 1024 * 1024 }).toString('utf8')
  .split('\n').filter(Boolean).map((line) => line.split('\t'));

// Per prefix, each town's ZIP Code points.
const prefixes = new Map();
for (const [, code, town, , state, , , , , lat, lon] of rows) {
  if (!/^\d{5}$/.test(code) || !state || /^[AFD]PO\b/.test(town)) continue;
  const towns = prefixes.get(code.slice(0, 3)) ?? new Map();
  prefixes.set(code.slice(0, 3), towns);
  const key = `${town}\t${state}`;
  towns.set(key, [...(towns.get(key) ?? []), [Number(lat), Number(lon)]]);
}

const round = (value) => Math.round(value * 1e3) / 1e3;
const placed = [];
for (const [prefix, towns] of [...prefixes].sort(([a], [b]) => a.localeCompare(b))) {
  const total = [...towns.values()].reduce((sum, points) => sum + points.length, 0);
  const [key, points] = [...towns].sort(([, a], [, b]) => b.length - a.length)[0];
  if (points.length < MIN_CODES || points.length * 2 <= total) continue;
  const [town, state] = key.split('\t');
  const mean = (index) => round(points.reduce((sum, point) => sum + point[index], 0) / points.length);
  placed.push([prefix, town, state, mean(0), mean(1)]);
}

const source = 'GeoNames US postal codes, CC BY 4.0. Generated by scripts/generate-zipcodes.mjs.';
const text = `{\n  "source": ${JSON.stringify(source)},\n  "prefixes": {\n${
  placed.map(([prefix, ...town]) => `    ${JSON.stringify(prefix)}: ${JSON.stringify(town)}`).join(',\n')}\n  }\n}\n`;
await writeFile(join(root, 'places/zipcodes.json'), text);
console.log(`zipcodes.json: ${placed.length} of ${prefixes.size} prefixes placed, ${Math.round(text.length / 1024)} KB`);
